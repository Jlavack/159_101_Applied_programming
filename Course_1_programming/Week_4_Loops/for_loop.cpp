#include <iostream>
using namespace std;

/*loops contian
- the test conditon
- an initialising variable
- a change to a variable(s)

For loops contain these three things inside the call
*/

int counter;

int main() {
  for (counter = 0; counter < 5; counter++) {
    cout << "Hello\n";
  }
}
// note how the initialising, condition and change are all in the brackets
